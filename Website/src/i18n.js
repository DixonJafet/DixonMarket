export function translate(language, key, values = {}) {
  const template = messages[language]?.[key] || messages.en[key] || key;
  return template.replace(/\{(\w+)\}/g, (_, name) => String(values[name] ?? ""));
}

export function translateError(language, message) {
  const normalizedMessage = message?.trim();
  const errorKeys = {
    "That user name is already registered.": "error.usernameTaken",
    "User name must be 3-50 characters and contain only letters, numbers, '.', '_' or '-'.": "error.usernameInvalid",
    "Password must be between 8 and 128 characters.": "error.passwordInvalid",
    "Invalid or expired bearer token.": "error.tokenInvalid",
    "Something went wrong. Please try again.": "error.request",
    "An error occurred while processing your request.": "error.request",
  };
  return translate(language, errorKeys[normalizedMessage] || "error.request");
}
